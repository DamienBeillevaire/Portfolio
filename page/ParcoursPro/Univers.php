                <h4>Mission de stage</h4>
                <div class="borderBottom">
                    <p>
                        DIP-O est une application qui a directement été créé à Nantes, permettant de onboardé plus rapide et plus simplement les centrales des clients.
                        Cependant, pour le moment, DIP-O est encore en cours de conception.
                        Ma mission était de créer un thème pour que l’application puisse ressembler un maximum au style de Bazefield.
                        Les langages de programmation que j’ai utiliser sont le TypeScript et React.
                    </p>
                    <p>
                        J’ai commencé par faire de la documentation pour lister les éléments qui devaient être stylisés (document PDF <a href="https://drive.google.com/file/d/1JW36e-zFbx3lEPCsi7X_pLGqwlpr2jSR/view?usp=sharing">ici</a>).
                    </p>
                    <p>Ensuite, pour facilité le changement de mode, je devais ajouter un bouton pour faire le changement entre le thème dark et le thème light.
                        J’ai donc analysé quel type de bouton je devais utiliser, via les composants proposés par MUI, pour cette fonctionnalité (document PDF <a href="https://drive.google.com/file/d/1c6bEATSrQDc9WzvNNLnw91e5dXNVAULD/view?usp=sharing">ici</a>).
                    </p>
                </div>
                <div class="borderBottom img-mag">
                    <h5>Button de changement de mode</h5>
                    <div>
                        <p>
                            Dans ce code, grâce à MaterialUI, je peux utiliser Checkbox/ et modifier ses propriétés.
                            Dans un premier temps, je lui donne une icône (soleil) quand la checkbox n’est pas cochée (mode light)
                            et je lui ajoute la couleur brandPrimary qui est définie dans mon fichier de thème.
                            Ensuite, je définis son icône (lune) quand la checkbox est cochée (mode dark), et de même je lui donne la couleur brandPrimary.
                            Ensuite, je dis que quand la checkbox est cochée, le mode du thème doit être dark. Et finalement, grâce au onChange,
                            je détecte si la checkbox change d’état et j’applique la fonction handleModeChange qui va géré tout le processus de changement de style sur l’application.
                        </p>
                        <img src="https://i.imageupload.app/b352787e7eebab30a14d.png" style="width: 60%" >
