        <h1>Mangatek</h1>
        <p>
            Mangatek est un projet développé au cours de ma formation au lycée La Colinière. Il s’agit d’un projet réalisé individuellement.

            L’application Mangatek est une bibliothèque en ligne regroupant des animés. Ces derniers sont affichés grâce à l’API Jikan, qui fournit une large base de données d’animés avec de nombreuses informations. Ces données sont utilisées afin de constituer une bibliothèque complète et accessible.

            Les utilisateurs peuvent ainsi consulter les informations sur les animés et ajouter leurs favoris pour retrouver facilement leurs contenus préférés.
        </p>
        <h3>Objectif : </h3>
        <p>
            L’objectif de ce projet est de développer une application qui recense une liste d’animés, avec la possibilité pour les utilisateurs d’ajouter certains animés à leurs favoris. Ce projet contiendra :
        </p>
        <ul>
            <li>Interagir avec une API afin d’afficher des données</li>
            <li>Disposer d’une interface utilisateur</li>
            <li>Lister les animés présents dans l’API</li>
            <li>Pouvoir ajouter des animés aux favoris</li>
        </ul>
