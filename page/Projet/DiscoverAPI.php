        <h1>Discover API</h1>
        <p>
            Discover API est un projet utilisé lors de ma formation au lycée La Colinière. Il découle du projet Ministage.
            Ministage est une application web qui permet aux élèves de collège ou de lycée de participer à une demi-journée dans un lycée afin de découvrir des formations.

            Cette application est destinée aux professeurs, aux élèves et aux établissements. Pour qu’un élève puisse effectuer un ministage, il doit en parler à son professeur référent.
            Par la suite, c’est ce dernier qui se charge de réserver le ministage.

            Chaque établissement peut proposer, ou non, un certain nombre de places pour accueillir des élèves en ministage.
        </p>
        <h3>Objectif : </h3>
        <p>
            L'objectif sur ce projet est de faire une application type API REST autour du projet Ministage. Ce projet contiendra :
        </p>
        <ul>
            <li>Des méthodes d'appelle pour accéder au donnée (GET|POST|PUT|DELETE)</li>
            <li>Une sécurisation via JWT Tokens</li>
        </ul>
