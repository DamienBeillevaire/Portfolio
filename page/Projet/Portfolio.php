        <h1>Portfolio</h1>
        <p>
            Le projet Portfolio est un projet développé au cours de ma formation au lycée La Colinière. Il s’agit d’un projet réalisé individuellement.
            L’objectif d’un portfolio est de présenter de manière claire et structurée qui je suis, mes compétences ainsi que les projets que j’ai réalisés.
            Il permet de mettre en valeur mon savoir-faire, ma progression et mon engagement dans mon domaine, tout en illustrant concrètement mes capacités à travers des exemples.
            Ce portfolio a également pour but de soutenir mon projet professionnel en montrant mes intérêts, mes objectifs et mon orientation future,
            notamment dans le cadre d’une recherche de stage, d’emploi ou de poursuite d’études.
