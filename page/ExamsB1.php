                <h2>Mission Principale</h2>
                <h3>Objectif : </h3>
                <div>
                    <p>
                        Dans un premier temps, le client demande la création d'un backend "template_fedex" capable d'interroger une BDD avec toutes les méthodes d'appel API GET/POST/PUT/DELETE d'une table crée au préalable afin de faire une interface utilisateur permettant de paramétrer des données dans une interface utilisateur. Pour cela, le client nous fournit une image qui montrerait à quoi devrais ressembler cette interface de paramétrage.
                        Et dans un second temps faire évoluer le web-service fedex présent dans DDP-DIT pour pouvoir copier les droits de modifications et de création associée au projet template_fedex
                    </p>
                    <img src="https://i.imageupload.app/0c158391ef09fee3e925.png">
